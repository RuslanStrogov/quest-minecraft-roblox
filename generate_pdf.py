FONT_PATH = r'C:\Windows\Fonts\ARIALUNI.ttf'
FONT_BOLD = r'C:\Windows\Fonts\ARIALUNI.ttf'

class QuestPDF(FPDF):
    def _setup_fonts(self):
        self.add_font('ArialUni', '', FONT_PATH, uni=True)
        self.add_font('ArialUni', 'B', FONT_BOLD, uni=True)
    
    def header(self):
        self.set_font('ArialUni', 'B', 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 5, 'КВЕСТ "МАЙНКРАФТ + ROBLOX" — День рождения двойняшек', new_x='LMARGIN', new_y='NEXT')
        self.line(10, 12, 200, 12)
        self.ln(5)
    
    def footer(self):
        self.set_y(-15)
        self.set_font('ArialUni', '', 8)
        self.set_text_color(150, 150, 150)
        self.cell(0, 10, f'Страница {self.page_no()}/{{nb}}', 0, 0, 'C')
    
    def section_title(self, title):
        self.set_font('ArialUni', 'B', 14)
        self.set_text_color(60, 40, 20)
        self.multi_cell(0, 8, title, 0, 'L')
        self.ln(2)
    
    def sub_title(self, title):
        self.set_font('ArialUni', 'B', 11)
        self.set_text_color(80, 60, 40)
        self.multi_cell(0, 7, title, 0, 'L')
        self.ln(1)
    
    def body_text(self, text):
        self.set_font('ArialUni', '', 9)
        self.set_text_color(40, 40, 40)
        self.multi_cell(0, 5, text, 0, 'L')
        self.ln(1)
    
    def bullet(self, text, indent=10):
        self.set_font('ArialUni', '', 9)
        self.set_text_color(40, 40, 40)
        x = self.get_x()
        self.set_x(x + indent)
        self.cell(5, 5, '•', 0, 0)  # bullet
        self.multi_cell(0, 5, text, 0, 'L')
        self.ln(0.5)
    
    def bold_body(self, text):
        self.set_font('ArialUni', 'B', 9)
        self.set_text_color(40, 40, 40)
        self.multi_cell(0, 5, text, 0, 'L')
        self.ln(0.5)
    
    def timeline_item(self, time, desc):
        self.set_font('ArialUni', 'B', 9)
        self.set_text_color(100, 60, 20)
        self.cell(25, 5, time, 0, 0)
        self.set_font('ArialUni', '', 9)
        self.set_text_color(40, 40, 40)
        self.multi_cell(0, 5, desc, 0, 'L')
        self.ln(1)

